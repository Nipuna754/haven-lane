import { defineArrayMember, defineField, defineType } from "sanity";

export const home = defineType({
  name: "home",
  title: "Listing",
  type: "document",
  groups: [
    { name: "basics", title: "Basics", default: true },
    { name: "details", title: "Details" },
    { name: "photos", title: "Photos" },
  ],
  fields: [
    defineField({ name: "address", type: "string", group: "basics", validation: (r) => r.required() }),
    defineField({
      name: "slug",
      title: "Web address",
      description: "Made from the street address. Click Generate.",
      type: "slug",
      group: "basics",
      options: { source: "address", maxLength: 80 },
      validation: (r) => r.required(),
    }),
    defineField({
      name: "status",
      type: "string",
      group: "basics",
      options: { list: [{ title: "For sale", value: "sale" }, { title: "For rent", value: "rent" }, { title: "Sold", value: "sold" }], layout: "radio", direction: "horizontal" },
      initialValue: "sale",
      validation: (r) => r.required(),
    }),
    defineField({
      name: "price",
      description: "Sale price in dollars. For rentals, the monthly rent.",
      type: "number",
      group: "basics",
      validation: (r) => r.required().positive().integer(),
    }),
    defineField({
      name: "label",
      title: "Badge",
      description: "Optional, e.g. “New listing” or “Price cut”. Leave empty to show the status.",
      type: "string",
      group: "basics",
      validation: (r) => r.max(24),
    }),
    defineField({ name: "neighbourhood", type: "reference", to: [{ type: "neighbourhood" }], group: "basics", validation: (r) => r.required() }),
    defineField({ name: "agent", type: "reference", to: [{ type: "agent" }], group: "basics", validation: (r) => r.required() }),
    defineField({ name: "featured", title: "Show on the home page", type: "boolean", group: "basics", initialValue: false }),
    defineField({ name: "listedAt", title: "Listed on", type: "date", group: "basics", initialValue: () => new Date().toISOString().slice(0, 10) }),

    defineField({
      name: "type",
      title: "Property type",
      type: "string",
      group: "details",
      options: { list: [{ title: "House", value: "house" }, { title: "Condo", value: "condo" }, { title: "Townhouse", value: "townhouse" }], layout: "radio", direction: "horizontal" },
      initialValue: "house",
      validation: (r) => r.required(),
    }),
    defineField({ name: "beds", title: "Bedrooms", type: "number", group: "details", validation: (r) => r.required().min(0).integer() }),
    defineField({ name: "baths", title: "Bathrooms", type: "number", group: "details", validation: (r) => r.required().min(0) }),
    defineField({ name: "sqft", title: "Floor area (sq ft)", type: "number", group: "details", validation: (r) => r.required().positive().integer() }),
    defineField({ name: "lotSqft", title: "Lot size (sq ft)", type: "number", group: "details" }),
    defineField({ name: "yearBuilt", title: "Year built", type: "number", group: "details", validation: (r) => r.min(1800).max(2100).integer() }),
    defineField({
      name: "summary",
      title: "One-line summary",
      description: "Shown under the address. One short sentence.",
      type: "string",
      group: "details",
      validation: (r) => r.required().max(110),
    }),
    defineField({
      name: "description",
      description: "Leave a blank line between paragraphs.",
      type: "text",
      rows: 8,
      group: "details",
      validation: (r) => r.required(),
    }),
    defineField({ name: "features", type: "array", of: [defineArrayMember({ type: "string" })], group: "details", options: { layout: "tags" } }),
    defineField({
      name: "location",
      title: "Map position",
      description: "Latitude and longitude, e.g. from Google Maps (right-click the house).",
      type: "geopoint",
      group: "details",
      validation: (r) => r.required(),
    }),

    defineField({
      name: "photos",
      description: "The first photo is the main one. Drag to reorder.",
      type: "array",
      of: [defineArrayMember({ type: "photo" })],
      group: "photos",
      options: { layout: "grid" },
      validation: (r) => r.min(1).warning("Add at least one photo."),
    }),
  ],
  orderings: [{ title: "Newest first", name: "listedDesc", by: [{ field: "listedAt", direction: "desc" }] }],
  preview: {
    select: { title: "address", status: "status", price: "price", media: "photos.0" },
    prepare: ({ title, status, price, media }) => ({
      title,
      subtitle: `${{ sale: "For sale", rent: "For rent", sold: "Sold" }[status as string] ?? ""}${price ? ` · $${Number(price).toLocaleString("en-US")}` : ""}`,
      media,
    }),
  },
});
